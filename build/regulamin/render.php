<li>przypadku umowy, która: (1) obejmuje wiele Produktów, które są dostarczane osobno, partiami lub w częściach – od</li>
<li>objęcia w posiadanie ostatniego Produktu, partii lub części albo (2) polega na regularnym dostarczaniu Produktów</li>
<li>przez czas oznaczony – od objęcia w posiadanie pierwszego z Produktów;</li>
<li>8.4.2. dla pozostałych umów – od dnia zawarcia umowy.</li>
<li>8.5. W przypadku odstąpienia od umowy zawartej na odległość umowę uważa się za niezawartą.</li>
<li>8.6. Produkty – rzeczy ruchome, w tym rzeczy ruchome z elementami cyfrowymi:</li>
<li>8.6.1. Sprzedawca ma obowiązek niezwłocznie, nie później niż w terminie 14 dni kalendarzowych od dnia otrzymania</li>
<li>oświadczenia konsumenta o odstąpieniu od umowy, zwrócić konsumentowi wszystkie dokonane przez niego płatności,</li>
<li>w tym koszty dostarczenia Produktu - rzeczy ruchomej, w tym rzeczy ruchomej z elementami cyfrowymi (z wyjątkiem</li>
<li>dodatkowych kosztów wynikających z wybranego przez konsumenta sposobu dostarczenia innego niż najtańszy</li>
<li>zwykły sposób dostawy dostępny w Sklepie Internetowym). Sprzedawca dokonuje zwrotu płatności przy użyciu takiego</li>
<li>samego sposobu płatności, jakiego użył konsument, chyba że konsument wyraźnie zgodził się na inny sposób zwrotu,</li>
<li>który nie wiąże się dla niego z żadnymi kosztami. W przypadku Produktów - rzeczy ruchomych (w tym rzeczy</li>
<li>ruchomych z elementami cyfrowymi) - jeżeli Sprzedawca nie zaproponował, że sam odbierze Produkt od konsumenta,</li>
