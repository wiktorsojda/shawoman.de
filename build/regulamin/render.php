<li>zobowiązany zaprzestać korzystania z tej treści cyfrowej lub usługi cyfrowej i udostępniania ich osobom trzecim.</li>
<li>8.8. Możliwe koszty związane z odstąpieniem przez konsumenta od umowy, które obowiązany jest ponieść konsument:</li>
