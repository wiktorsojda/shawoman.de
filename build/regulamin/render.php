<li class="regulamin-list-title">6. PROCEDURA ROZPATRYWANIA REKLAMACJI</li>
<li></li>
<li>6.1. Niniejszy punkt 6. Regulaminu określa procedurę rozpatrywania reklamacji wspólną dla wszystkich reklamacji</li>
<li>składanych do Sprzedawcy, w szczególności reklamacji dotyczących Produktów, Umów Sprzedaży, Usług</li>
<li>Elektronicznych oraz pozostałych reklamacji związanych z działaniem Sprzedawcy lub Sklepu Internetowego.</li>
<li>6.2. Reklamacja może zostać złożona na przykład:</li>
<li>6.2.1. pisemnie na adres: ul. Krakowska 118, 32-051 Jaśkowice;</li>
<li>6.2.2. w formie elektronicznej za pośrednictwem poczty elektronicznej na adres: kontakt@shavwoman.pl.</li>
<li>6.3. Przesłanie lub zwrot Produktu w ramach reklamacji może nastąpić na adres: Krakowska 118, 32-051 Jaśkowice</li>
<li>6.4. Zaleca się podanie w opisie reklamacji: (1) informacji i okoliczności dotyczących przedmiotu reklamacji, w szczególności</li>
<li>rodzaju i daty wystąpienia nieprawidłowości lub braku zgodności z umową; (2) żądania sposobu doprowadzenia do</li>
<li>zgodności z umową lub oświadczenia o obniżeniu ceny albo odstąpieniu od umowy (zwrotu pieniędzy) lub innego roszczenia; oraz (3)</li>
<li>danych kontaktowych składającego reklamację – ułatwi to i przyspieszy rozpatrzenie reklamacji. Wymogi podane w</li>
<li>zdaniu poprzednim mają formę jedynie zalecenia i nie wpływają na skuteczność reklamacji złożonych z pominięciem</li>
<li>zalecanego opisu reklamacji.</li>
<li>6.5. W razie zmiany podanych danych kontaktowych przez składającego reklamację w trakcie rozpatrywania reklamacji</li>
<li>zobowiązany jest on do powiadomienia o tym Sprzedawcy.</li>
<li>6.6. Do reklamacji mogą zostać załączone przez składającego reklamację dowody (np. zdjęcia, dokumenty lub Produkt)</li>
<li>związane z przedmiotem reklamacji. Sprzedawca może także zwrócić się do składającego reklamację z prośbą o</li>
<li>podanie dodatkowych informacji lub przesłanie dowodów (np. zdjęcia), jeżeli ułatwi to i przyspieszy rozpatrzenie</li>
<li>reklamacji przez Sprzedawcę.</li>
<li>6.7. Sprzedawca ustosunkuje się do reklamacji niezwłocznie, nie później niż w terminie 14 dni kalendarzowych od dnia jej</li>
<li>otrzymania.</li>
<li>6.8. Podstawa i zakres odpowiedzialności ustawowej Sprzedawcy są określone powszechnie obowiązującymi przepisami</li>
<li>prawa, w szczególności w Kodeksie Cywilnym, Ustawie o Prawach Konsumenta oraz ustawie o świadczeniu usług drogą elektroniczną z dnia 18 lipca 2002 r. (Dz.U. Nr 144, poz. 1204 ze zm.). Poniżej wskazane są dodatkowe informacje</li>
<li>dotyczące przewidzianej przez prawo odpowiedzialności Sprzedawcy za zgodność Produktu z Umową Sprzedaży:</li>
<li>6.8.1. W przypadku reklamacji Produktu – rzeczy ruchomej – zakupionego przez Klienta na podstawie Umowy Sprzedaży</li>
<li>zawartej ze Sprzedawcą do dnia 31. grudnia 2022 r. określają przepisy Kodeksu Cywilnego w brzmieniu</li>
<li>obowiązującym do dnia 31. grudnia 2022 r., w szczególności art. 556-576 Kodeksu Cywilnego. Przepisy te określają w</li>
<li>szczególności podstawę i zakres odpowiedzialności Sprzedawcy względem Klienta, jeżeli sprzedany Produkt ma wadę</li>
<li>fizyczną lub prawną (rękojmia). Zgodnie z art. 558 § 1 Kodeksu Cywilnego odpowiedzialność Sprzedawcy z tytułu</li>
<li>rękojmi za Produkt zakupiony zgodnie ze zdaniem poprzednim wobec Klienta niebędącego konsumentem zostaje</li>
<li>wyłączona.</li>
<li>6.8.2. W przypadku reklamacji Produktu – rzeczy ruchomej (w tym rzeczy ruchomej z elementami cyfrowymi), z</li>
<li>wyłączeniem jednak rzeczy ruchomej, która służy wyłącznie jako nośnik treści cyfrowej – zakupionego przez Klienta na</li>
<li>podstawie Umowy Sprzedaży zawartej ze Sprzedawcą od dnia 1. stycznia 2023 r. określają przepisy Ustawy o</li>
<li>Prawach Konsumenta w brzmieniu obowiązującym od dnia 1. stycznia 2023 r., w szczególności art. 43a - 43g Ustawy</li>
<li>o Prawach Konsumenta. Przepisy te określają w szczególności podstawę i zakres odpowiedzialności Sprzedawcy</li>
<li>względem konsumenta, w razie braku zgodności Produktu z Umową Sprzedaży.</li>
<li>6.8.3. W przypadku reklamacji Produktu – treści lub usługi cyfrowej lub rzeczy ruchomej, która służy wyłącznie jako</li>
<li>nośnik treści cyfrowej – zakupionego przez Klienta na podstawie Umowy Sprzedaży zawartej ze Sprzedawcą od</li>
<li>dnia 1. stycznia 2023 r. lub przed tym dniem, jeżeli dostarczanie takiego Produktu miało nastąpić lub nastąpiło po tym</li>
<li>dniu określają przepisy Ustawy o Prawach Konsumenta w brzmieniu obowiązującym od dnia 1. stycznia 2023 r., w</li>
<li>szczególności art. 43h – 43q Ustawy o Prawach Konsumenta. Przepisy te określają w szczególności podstawę i zakres</li>
<li>odpowiedzialności Sprzedawcy względem konsumenta, w razie braku zgodności Produktu z Umową Sprzedaży.</li>
<li>6.9. Poza odpowiedzialnością ustawową na Produkt może zostać udzielona gwarancja – jest to odpowiedzialność umowna</li>
<li>(dodatkowa) i można z niej skorzystać, gdy dany Produkt jest objęty gwarancją. Gwarancja może być udzielona przez</li>
<li>inny podmiot niż Sprzedawca (np. przez producenta lub dystrybutora). Szczegółowe warunki dotyczące</li>
<li>odpowiedzialności na podstawie gwarancji, w tym także dane podmiotu odpowiedzialnego za realizację gwarancji oraz</li>
<li>podmiotu uprawnionego do skorzystania z niej są dostępne w opisie gwarancji, np. w karcie gwarancyjnej lub w innym</li>
<li>miejscu dotyczącym udzielenia gwarancji. Sprzedawca wskazuje, że w przypadku braku zgodności Produktu z umową</li>
<li>Klientowi z mocy prawa przysługują środki ochrony prawnej ze strony i na koszt Sprzedawcy oraz że gwarancja nie ma</li>
<li>wpływu na te środki ochrony prawnej.</li>
<li>6.10. Zawarte w punktach 6.8.2. i 6.8.3 Regulaminu postanowienia dotyczące konsumenta stosuje się również do Klienta</li>
<li>będącego osobą fizyczną zawierającą umowę bezpośrednio związaną z jej działalnością gospodarczą, gdy z treści tej</li>
