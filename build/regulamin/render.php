<li>8.4. Bieg terminu do odstąpienia od umowy rozpoczyna się:</li>
<li>8.4.1. dla umowy, w wykonaniu której Sprzedawca wydaje Produkt, będąc zobowiązany do przeniesienia jego własności – od</li>
