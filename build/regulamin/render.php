<li>lub usługi cyfrowej, w szczególności przez uniemożliwienie konsumentowi dostępu do treści cyfrowych lub usługi</li>
<li>cyfrowej lub zablokowanie konta użytkownika, co nie ma wpływu na uprawnienia konsumenta, o których mowa w</li>
<li>zdaniu poprzednim. Konsument ma prawo odzyskać treści cyfrowe od Sprzedawcy nieodpłatnie, bez przeszkód ze strony Sprzedawcy, w rozsądnym terminie i powszechnie używanym formacie przeznaczonym do odczytu</li>
