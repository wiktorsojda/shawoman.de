<li class="regulamin-list-title">5. PROFILOWANIE W SKLEPIE INTERNETOWYM</li>

<li>5.1. Rozporządzenie RODO nakłada na Administratora obowiązek informowania o zautomatyzowanym podejmowaniu</li>
<li>decyzji, w tym o profilowaniu, o którym mowa w art. 22 ust. 1 i 4 Rozporządzenia RODO, oraz – przynajmniej w tych</li>
<li>przypadkach – istotne informacje o zasadach ich podejmowania, a także o znaczeniu i przewidywanych</li>
<li>konsekwencjach takiego przetwarzania dla osoby, której dane dotyczą. Mając to na uwadze, Administrator podaje w</li>
<li>tym punkcie polityki prywatności informacje dotyczące możliwego profilowania.</li>
<li>5.2. Administrator może korzystać w Sklepie Internetowym z profilowania do celów marketingu bezpośredniego, ale decyzje</li>
<li>podejmowane na jego podstawie przez Administratora nie dotyczą zawarcia lub odmowy zawarcia Umowy Sprzedaży</li>
<li>czy też możliwości korzystania z Usług Elektronicznych w Sklepie Internetowym. Efektem korzystania z profilowania w</li>
<li>Sklepie Internetowym może być np. przyznanie danej osobie rabatu, przesłanie jej kodu rabatowego, przypomnienie o</li>
<li>niedokończonych zakupach, przesłanie propozycji Produktu, który może odpowiadać zainteresowaniom lub</li>
<li>preferencjom danej osoby lub też zaproponowanie lepszych warunków w porównaniu do standardowej oferty Sklepu</li>
<li>Internetowego. Mimo profilowania to dana osoba podejmuje swobodnie decyzję, czy będzie chciała skorzystać z</li>
<li>otrzymanego w ten sposób rabatu, czy też lepszych warunków i dokonać zakupu w Sklepie Internetowym.</li>
<li>5.3. Profilowanie w Sklepie Internetowym polega na automatycznej analizie lub prognozie zachowania danej osoby na</li>
<li>stronie Sklepu Internetowego np. poprzez dodanie konkretnego Produktu do koszyka, przeglądanie strony konkretnego</li>
<li>Produktu w Sklepie Internetowym czy też poprzez analizę dotychczasowej historii dokonanych zakupów w Sklepie</li>
<li>Internetowym. Warunkiem takiego profilowania jest posiadanie przez Administratora danych osobowych danej osoby,</li>
<li>aby móc jej następnie przesłać np. kod rabatowy.</li>
<li>5.4. Osoba, której dane dotyczą, ma prawo do tego, by nie podlegać decyzji, która opiera się wyłącznie na</li>
<li>zautomatyzowanym przetwarzaniu, w tym profilowaniu, i wywołuje wobec tej osoby skutki prawne lub w podobny</li>
<li>sposób istotnie na nią wpływa.</li>

