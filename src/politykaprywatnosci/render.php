<li>żądania od Administratora dostępu do swoich danych osobowych, ich sprostowania, usunięcia („prawo do bycia</li>
<li>zapomnianym”) lub ograniczenia przetwarzania oraz ma prawo do wniesienia sprzeciwu wobec przetwarzania, a także</li>
<li>ma prawo do przenoszenia swoich danych. Szczegółowe warunki wykonywania wskazanych wyżej praw wskazane są</li>
<li>w art. 15-21 Rozporządzenia RODO.</li>
<li>6.2. Prawo do cofnięcia zgody w dowolnym momencie – osoba, której dane przetwarzane są przez Administratora na</li>
<li>podstawie wyrażonej zgody (na podstawie art. 6 ust. 1 lit. a) lub art. 9 ust. 2 lit. a) Rozporządzenia RODO), ma prawo</li>
<li>do cofnięcia zgody w dowolnym momencie bez wpływu na zgodność z prawem przetwarzania, którego dokonano na</li>
<li>podstawie zgody przed jej cofnięciem.</li>
<li>6.3. Prawo wniesienia skargi do organu nadzorczego – osoba, której dane przetwarzane są przez Administratora, ma</li>
<li>prawo wniesienia skargi do organu nadzorczego w sposób i trybie określonym w przepisach Rozporządzenia RODO</li>
<li>oraz prawa polskiego, w szczególności ustawy o ochronie danych osobowych. Organem nadzorczym w Polsce jest</li>
<li>Prezes Urzędu Ochrony Danych Osobowych.</li>
<li>6.4. Prawo do sprzeciwu – osoba, której dane dotyczą, ma prawo w dowolnym momencie wnieść sprzeciw – z przyczyn</li>
<li>związanych z jej szczególną sytuacją – wobec przetwarzania dotyczących jej danych osobowych opartego na art. 6</li>
<li>ust. 1 lit. e) (interes lub zadania publiczne) lub f) (prawnie uzasadniony interes administratora), w tym profilowania na</li>
<li>podstawie tych przepisów. Administratorowi w takim przypadku nie wolno już przetwarzać tych danych osobowych,</li>
<li>chyba że wykaże on istnienie ważnych prawnie uzasadnionych podstaw do przetwarzania, nadrzędnych wobec</li>
<li>interesów, praw i wolności osoby, której dane dotyczą, lub podstaw do ustalenia, dochodzenia lub obrony roszczeń.</li>
<li>6.5. Prawo do sprzeciwu dot. marketingu bezpośredniego – jeżeli dane osobowe są przetwarzane na potrzeby</li>
<li>marketingu bezpośredniego, osoba, której dane dotyczą, ma prawo w dowolnym momencie wnieść sprzeciw wobec</li>
